        titles_seen = set()

        def add_item(title: str, year: str, type_name: str, remarks: str, size_gb: int, is_series: bool = False):
            if title in titles_seen:
                return
            titles_seen.add(title)
            size_bytes = int(size_gb * 1024 * 1024 * 1024)
            items.append({
                "title": title,
                "year": str(year),
                "type_name": type_name,
                "remarks": remarks,
                "has_4k": True,
                "is_pan": False,
                "source_count": 3,
                "size_bytes": size_bytes,
                "direct_play_url": f"https://mock-4k.ikan.internal/{title}.m3u8"
            })

        # 1. 核心高分 4K 电影
        for title, yr, rmk, sz in CORE_4K_MOVIES:
            add_item(title, yr, "4K电影", rmk, sz, is_series=False)

        # 2. 核心高分 4K 剧集
        for title, yr, rmk, sz in CORE_4K_SERIES:
            add_item(title, yr, "4K剧集", rmk, sz, is_series=True)

        # 3. 核心 4K 动漫
        for title, yr, rmk, sz in CORE_4K_ANIMES:
            add_item(title, yr, "4K动漫", rmk, sz, is_series=True)

        # 4. 核心 4K 纪录片
        for title, yr, rmk, sz in CORE_4K_DOCS:
            add_item(title, yr, "4K纪录片", rmk, sz, is_series=True)

