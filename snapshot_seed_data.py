    @classmethod
    def generate_pan_catalog(cls) -> List[Dict[str, Any]]:
        """生成 1200+ 部带有直通网盘资源的结构化快照条目"""
        pan_types = ["夸克网盘", "阿里云盘", "百度网盘", "迅雷云盘"]
        items_4k = cls.generate_4k_catalog()
        pan_items: List[Dict[str, Any]] = []

        for idx, item in enumerate(items_4k):
            pan_name = pan_types[idx % len(pan_types)]
            raw_type = item.get("type_name", "电影")
            # 转换类型标签为网盘专区标准
            if "动漫" in raw_type:
                pan_cat = "网盘动漫"
            elif "纪录" in raw_type:
                pan_cat = "网盘纪录片"
            elif "剧" in raw_type:
                pan_cat = "网盘剧集"
            else:
                pan_cat = "网盘电影"

            title = item["title"]
            pan_items.append({
                "title": title,
                "year": item.get("year", "2024"),
                "type_name": pan_cat,
                "remarks": f"[{pan_name}] 4K杜比原画·秒存即看",
                "has_4k": True,
                "is_pan": True,
                "pan_url": f"https://pan.example.com/{pan_name[:2]}/{idx + 10001}",
                "source_count": 2,
                "size_bytes": item.get("size_bytes", 25 * 1024 * 1024 * 1024)
            })

        return pan_items
